from math import *

x = float(input('Введите: x='))

print("x=",x)

def f(a,b,x):
    return a*sin(x) + b*cos(x)

y = 4*sin(x) + f(5,3,x)/f(8,4,x)

y1 = tan(x) + f(1.3,1.8,x)/f(2.5,-4.5,x)

print('y=',y,'y1=',y1)
