# 13. Змейка-1
# Напишите программу, которая заполняет матрицу из N строк и M столбцов
# натуральными числами змейкой, как показано в примере.

# Входные данные
# Входная строка содержит числа N и M ( 1 ≤ N , M ≤ 100 ), разделённые пробелом.

# Выходные данные
# Программа должна вывести матрицу, заполненную заданным способом.

# Примеры
# входные данные
# 4 5

# выходные данные
# 1 2 3 4 5
# 10 9 8 7 6
# 11 12 13 14 15
# 20 19 18 17 16

n = int(input("Введите количество строк: "))
m = int(input("Введите количество столбцов: "))

matrix = [[i+n for n in range(m)] for i in range(1, n*m+1, m)]
for j in range(len(matrix)):
    if j%2 == 1: matrix[j].reverse()
    
print(*matrix, sep='\n')
