# Переменные:
#   CONST_D - граница диапазона случайных чисел
#   r, c - число строк и столбцов матрицы
#   n, k - номера столбцов, в которых обнуляются положительные элементы
#   a - матрица
#   q - номер обрабатываемого столбца (n или k)
#   col - q-й столбец матрицы, одномерный массив
#   i - номер строки

import random
CONST_D = 100


def MatIn(r, c):
    """
    Функция ввода матрицы (заполнение случайными целыми числами)
    Входные параметры:
        r, c - число строк и столбцов матрицы
    Выходные параметры:
        a - матрица
    """
    a = [[0] * c for i in range(r)]
    for i in range(r):
        for j in range(c):
            a[i][j] = random.randint(-CONST_D, CONST_D)
    return a


def MatOut(a):
    """
    Процедура вывода матрицы
    Входные параметры:
        a - матрица
    """
    for row in a:
        for x in row:
            print(f'{x:5}', end='')
        print()


def Res(b):
    """
    Процедура обнуления положительных элементов одномерного массива
    Входные параметры:
        b - одномерный массив (изменяется на месте)
    """
    for p in range(len(b)):
        if b[p] > 0:
            b[p] = 0


r = int(input('Введите количество строк матрицы: '))
c = int(input('Введите количество столбцов матрицы: '))
n = int(input('Введите номер столбца n: '))
k = int(input('Введите номер столбца k: '))

a = MatIn(r, c)
print('Исходная матрица:')
MatOut(a)

for q in (n - 1, k - 1):
    col = [0] * r
    for i in range(r):
        col[i] = a[i][q]
    Res(col)
    for i in range(r):
        a[i][q] = col[i]

print('Результирующая матрица:')
MatOut(a)
