# Переменные:
#   s - исходное символьное множество
#   d - множество цифр
#   b - множество букв
#   sp - множество специальных символов
#   ch - элемент множества s
#   flag - признак того, что пустое множество найдено

s = set(input('Введите символы: '))

d = set()
b = set()
sp = set()
for ch in s:
    if '0' <= ch <= '9':
        d.add(ch)
    elif 'a' <= ch <= 'z' or 'A' <= ch <= 'Z' or 'А' <= ch <= 'я' or ch in 'ёЁ':
        b.add(ch)
    else:
        sp.add(ch)

print('Цифры:', *sorted(d))
print('Буквы:', *sorted(b))
print('Специальные символы:', *sorted(sp))

flag = False
if d == set():
    print('Множество цифр пустое')
    flag = True
if b == set():
    print('Множество букв пустое')
    flag = True
if sp == set():
    print('Множество специальных символов пустое')
    flag = True
if not flag:
    print('Пустых множеств нет')
