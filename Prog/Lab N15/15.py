# Переменные:
#   entries - количество элементов словаря
#   d - исходный словарь
#   i - номер элемента
#   key - ключ очередного элемента
#   value - значение очередного элемента
#   max_key - ключ элемента с максимальным значением

entries = int(input('Количество элементов: '))

d = {}
for i in range(entries):
    key = input(f'Ключ {i}: ')
    value = float(input(f'Значение {i}: '))
    d[key] = value

if d:
    max_key = max(d, key=d.get)
    del d[max_key]

print(d)
