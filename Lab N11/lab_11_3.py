# Переменные:
#   k - исходный кортеж
#   n - удаляемый элемент
#   i - номер элемента кортежа
#   pos - номер первого появления элемента n (-1, если его нет)

k = tuple(map(int, input().split()))
n = int(input())

pos = -1
for i in range(len(k)):
    if k[i] == n:
        pos = i
        break

if pos != -1:
    print(k[:pos] + k[pos + 1:])
else:
    print(k)
