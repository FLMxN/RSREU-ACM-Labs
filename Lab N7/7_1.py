from math import *

def f(x):
    match x:
        case _ if -3 <= x <= 3:
            return 1+sqrt(9-x**2)
        case _ if 3 < x <= 7:
            return 1+sqrt(4-(x-5)**2)
        case _ if 7 < x <= 9:
            return 1+sqrt(1-(x-8)**2)
        case _:
            return 1

x0 = int(input("Введите точку старта: "))
h = int(input("Введите шаг: "))
n = int(input("Введите точку финиша: "))
p = 1
s = 0

x = 0
while x < n + h/3: 
    y = f(x)
    p = p*y
    s = s + y
    x += h

print("P = %.2f, S = %.2f" % (p, s))