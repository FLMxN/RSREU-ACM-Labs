# x0 - точка старта, h - шаг, xn - точка финиша
# a - расстояние, k - число точек
# xv - икс вершины параболы, yv - игрек вершины параболы

from math import *

x0 = float(input("Введите точку старта: "))
h = float(input("Введите шаг: "))
xn = float(input("Введите точку финиша: "))
a = float(input("Введите расстояние: "))

x = x0
k = 0
while x < xn + h/5: 
    y = x**2 + 2*x + 2 # f(x)
    xv = -2/(2*2) # -b/2a
    yv = xv**2 + 2*xv + 2 # f(xv)
    if sqrt((x-xv)**2 + (y-yv)**2) >= a: # евклидово расстояние
        k += 1
    x += h

print(k)