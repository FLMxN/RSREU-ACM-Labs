# Переменные:
#   x0, xn, hx - начальное, конечное значение аргумента и шаг
#   x, y - аргумент и значение функции
#   ch, zn - числитель и знаменатель дроби
#   S, P - сумма и произведение значений функции
#   eps - точность сравнения с нулем

eps = 0.000001

x0 = float(input('Введите x0='))
xn = float(input('Введите xn='))
hx = float(input('Введите hx='))

S = 0
P = 1
x = x0

print('     x            y')
while x <= xn + eps:
    if x > 1.75:
        ch = (x + 5) * (x - 6)
        zn = (x - 2) * (x + 3)
    else:
        ch = x**2 + 2 * x + 4
        zn = x**2 - 2 * x + 1
    if zn == 0:
        print('%8.3f   точка разрыва' % x)
    else:
        y = ch / zn
        print('%8.3f %12.6f' % (x, y))
        S = S + y
        P = P * y
    x += hx

print('Сумма S =', S)
print('Произведение P =', P)
