# Переменные:
#   i - количество слогаемых
#   n - параметр цикла
#   x, a - переменные
#   S - сумма
#   F - значение выражения

x = float(input('Введите x='))
a = float(input('Введите a='))

S = 0
for n in range(0, 7):
    S = S + (x + a) ** (n / 2)

F = (a + x) / 3 * S
print('F =', F)
