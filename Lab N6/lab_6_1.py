# Переменные:
#   a10, a20, an - начальный и конечный, текущий эллемент последрвательности
#   n = параметр цикла

from math import sqrt 

a10 = 10
a20 = 20

for n in range(a10, a20 + 1):
    an = sqrt(n**2 + 1)
    print('a%d = %f' % (n, an))