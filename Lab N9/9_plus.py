# 13. Переставить соседние
# Переставьте соседние элементы списка (A[0] c A[1], A[2] c A[3] и т.д.). Если
# элементов нечетное число, то последний элемент остается на своем месте.

# Входные данные
# Вводится список чисел. Все числа списка находятся на одной строке.

# Выходные данные
# Выведите ответ на задачу.

array = list(map(int, input("Чиселки: ").split()))

for i in range(len(array)):
    if i%2 == 1: array[i], array[i-1] = array[i-1], array[i]

print(*array)